// Procedural contour tile for the roadmap canvas (T-024). Deterministic: same seed, same output.
// Usage: node scripts/gen-contour-tile.mjs  (rewrites apps/web/components/roadmap/contour-tile.ts)
// Closed wobbly rings around two centres; rings that cross the tile edge are drawn at 9 offsets
// by ContourLayer, so the pattern is seamless.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const W = 480;
const H = 320;
const SEED = 24;
function rng(a) {
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = rng(SEED);
const centres = [
  { x: 110, y: 90, radii: [28, 52, 78, 106] },
  { x: 360, y: 230, radii: [24, 46, 70, 96, 124] },
];
const N = 9;

function ring(cx, cy, r) {
  const phase = rand() * Math.PI * 2;
  const k = 2 + Math.floor(rand() * 2);
  const amp = 0.1 + rand() * 0.08;
  const pts = [];
  for (let i = 0; i < N; i++) {
    const a = (i / N) * Math.PI * 2;
    const rr = r * (1 + amp * Math.sin(k * a + phase) + (rand() - 0.5) * 0.05);
    pts.push([cx + rr * Math.cos(a) * 1.25, cy + rr * Math.sin(a)]);
  }
  // Closed Catmull-Rom to cubic Bezier.
  const f = (n) => Math.round(n);
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (let i = 0; i < N; i++) {
    const p0 = pts[(i - 1 + N) % N];
    const p1 = pts[i];
    const p2 = pts[(i + 1) % N];
    const p3 = pts[(i + 2) % N];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return d + "Z";
}

const paths = centres.flatMap((c) => c.radii.map((r) => ring(c.x, c.y, r)));
const src = `// GENERATED by scripts/gen-contour-tile.mjs (seed ${SEED}). Do not edit by hand.
// Seamless ${W}x${H} contour tile: closed rings; ContourLayer draws them at 9 offsets so edge-crossing rings wrap.
export const CONTOUR_TILE = {
  width: ${W},
  height: ${H},
  paths: ${JSON.stringify(paths, null, 4).replace(/\n\]/, "\n  ]")},
} as const;
`;
const out = fileURLToPath(
  new globalThis.URL("../apps/web/components/roadmap/contour-tile.ts", import.meta.url),
);
writeFileSync(out, src);
